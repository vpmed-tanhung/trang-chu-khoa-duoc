-- BHYT non-pickup module — schema, aggregation and reconciliation.
-- Safe to run over the first version: existing columns/data are preserved.

create table if not exists public.bhyt_nonpickup_cases (
  record_key text primary key,
  dispense_date date not null,
  serial_no text,
  patient_name text not null,
  phone text,
  reason text not null,
  reason_group text not null,
  source_file text,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.bhyt_nonpickup_cases
  add column if not exists visit_code text,
  add column if not exists prescription_no text,
  add column if not exists insurance_code text,
  add column if not exists diagnosis text,
  add column if not exists total_quantity numeric(18,3) not null default 0,
  add column if not exists total_amount numeric(18,2) not null default 0,
  add column if not exists insurance_amount numeric(18,2) not null default 0,
  add column if not exists patient_amount numeric(18,2) not null default 0;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'bhyt_nonpickup_cases_reason_group_check'
      and conrelid = 'public.bhyt_nonpickup_cases'::regclass
  ) then
    alter table public.bhyt_nonpickup_cases add constraint bhyt_nonpickup_cases_reason_group_check
      check (reason_group in (
        'Quên/không lấy', 'Mua ngoài', 'Không biết/chưa rõ',
        'Không liên lạc được', 'Không đi khám/nghỉ', 'Khác'
      ));
  end if;
end $$;

create table if not exists public.bhyt_nonpickup_items (
  id bigint generated by default as identity primary key,
  case_record_key text not null references public.bhyt_nonpickup_cases(record_key) on delete cascade,
  line_no integer not null,
  drug_code text,
  drug_name text not null,
  unit text not null default 'viên',
  quantity numeric(18,3) not null check (quantity >= 0),
  unit_price numeric(18,4) not null default 0 check (unit_price >= 0),
  total_amount numeric(18,2) not null default 0 check (total_amount >= 0),
  insurance_amount numeric(18,2) not null default 0 check (insurance_amount >= 0),
  patient_amount numeric(18,2) not null default 0 check (patient_amount >= 0),
  created_at timestamptz not null default now(),
  unique (case_record_key, line_no)
);

create table if not exists public.bhyt_monthly_inventory (
  id bigint generated by default as identity primary key,
  inventory_month date not null check (inventory_month = date_trunc('month', inventory_month)::date),
  drug_code text not null,
  drug_name text not null,
  unit text not null default 'viên',
  opening_quantity numeric(18,3) not null default 0,
  received_quantity numeric(18,3) not null default 0,
  actual_issued_quantity numeric(18,3) not null default 0,
  book_closing_quantity numeric(18,3) not null default 0,
  physical_closing_quantity numeric(18,3),
  nonpickup_in_issued boolean not null default true,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (inventory_month, drug_code)
);

create index if not exists bhyt_nonpickup_cases_date_idx on public.bhyt_nonpickup_cases (dispense_date);
create index if not exists bhyt_nonpickup_cases_reason_group_idx on public.bhyt_nonpickup_cases (reason_group);
create index if not exists bhyt_nonpickup_items_case_idx on public.bhyt_nonpickup_items (case_record_key);
create index if not exists bhyt_nonpickup_items_drug_idx on public.bhyt_nonpickup_items (drug_code);
create index if not exists bhyt_monthly_inventory_month_idx on public.bhyt_monthly_inventory (inventory_month);

