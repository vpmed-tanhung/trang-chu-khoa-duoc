create or replace function public.bhyt_refresh_case_totals(p_record_key text)
returns void language sql security invoker set search_path = public as $$
  update public.bhyt_nonpickup_cases c
  set total_quantity = x.total_quantity,
      total_amount = x.total_amount,
      insurance_amount = x.insurance_amount,
      patient_amount = x.patient_amount
  from (
    select coalesce(sum(quantity), 0) as total_quantity,
           coalesce(sum(total_amount), 0) as total_amount,
           coalesce(sum(insurance_amount), 0) as insurance_amount,
           coalesce(sum(patient_amount), 0) as patient_amount
    from public.bhyt_nonpickup_items
    where case_record_key = p_record_key
  ) x
  where c.record_key = p_record_key;
$$;

create or replace function public.bhyt_items_refresh_after_insert()
returns trigger language plpgsql security invoker set search_path = public as $$
declare v_key text;
begin
  for v_key in select distinct case_record_key from new_rows loop
    perform public.bhyt_refresh_case_totals(v_key);
  end loop;
  return null;
end;
$$;

create or replace function public.bhyt_items_refresh_after_delete()
returns trigger language plpgsql security invoker set search_path = public as $$
declare v_key text;
begin
  for v_key in select distinct case_record_key from old_rows loop
    perform public.bhyt_refresh_case_totals(v_key);
  end loop;
  return null;
end;
$$;

create or replace function public.bhyt_items_refresh_after_update()
returns trigger language plpgsql security invoker set search_path = public as $$
declare v_key text;
begin
  for v_key in
    select case_record_key from new_rows union select case_record_key from old_rows
  loop
    perform public.bhyt_refresh_case_totals(v_key);
  end loop;
  return null;
end;
$$;

