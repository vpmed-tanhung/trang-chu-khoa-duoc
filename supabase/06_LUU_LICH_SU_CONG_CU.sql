returns table (
  user_id uuid,
  email text,
  full_name text,
  job_title text,
  department text,
  role text
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    staff.user_id,
    users.email::text,
    staff.full_name,
    staff.job_title,
    staff.department,
    staff.role
  from public.pharmacy_staff_members as staff
  join auth.users as users on users.id = staff.user_id
  where staff.user_id = auth.uid();
$$;

revoke all on function public.get_my_pharmacy_staff_profile() from public;
grant execute on function public.get_my_pharmacy_staff_profile() to authenticated;

