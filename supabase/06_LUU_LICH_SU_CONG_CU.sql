-- 3. Trigger chỉ tin định danh của phiên đăng nhập, không tin dữ liệu client.
create or replace function public.fill_renal_lookup_identity()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_staff record;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  select
    staff.user_id,
    staff.full_name,
    staff.job_title,
    staff.department,
    users.email
  into current_staff
  from public.pharmacy_staff_members as staff
  join auth.users as users on users.id = staff.user_id
  where staff.user_id = auth.uid();

  if not found then
    raise exception 'Pharmacy staff permission required';
  end if;

  new.user_id := auth.uid();
  new.patient_code := upper(trim(coalesce(nullif(new.patient_code, ''), 'KHONG_CO_MA')));
  if char_length(new.patient_code) < 1 or char_length(new.patient_code) > 30 then
    raise exception 'Mã bệnh nhân phải có từ 1 đến 30 ký tự';
  end if;
  new.staff_name := current_staff.full_name;
  new.staff_email := current_staff.email;
  new.job_title := current_staff.job_title;
  new.department := current_staff.department;
  new.created_at := now();
  return new;
end;
$$;

revoke all on function public.fill_renal_lookup_identity() from public;

drop trigger if exists set_renal_lookup_identity on public.renal_lookup_logs;
create trigger set_renal_lookup_identity
before insert on public.renal_lookup_logs
for each row execute function public.fill_renal_lookup_identity();

-- 4. RLS: nhân viên Khoa Dược đọc/ghi; chỉ admin được xóa.
alter table public.renal_lookup_logs enable row level security;

drop policy if exists "approved users insert own renal lookups" on public.renal_lookup_logs;
drop policy if exists "pharmacy staff insert calculation logs" on public.renal_lookup_logs;
create policy "pharmacy staff insert calculation logs"
on public.renal_lookup_logs
for insert
to authenticated
with check (
  user_id = auth.uid()
  and public.is_pharmacy_staff()
);

drop policy if exists "approved users read shared renal lookup history" on public.renal_lookup_logs;
drop policy if exists "admins read renal lookup audit" on public.renal_lookup_logs;
drop policy if exists "pharmacy staff read calculation logs" on public.renal_lookup_logs;
create policy "pharmacy staff read calculation logs"
on public.renal_lookup_logs
for select
to authenticated
using (public.is_pharmacy_staff());

drop policy if exists "admins delete shared renal lookup history" on public.renal_lookup_logs;
drop policy if exists "pharmacy admins delete calculation logs" on public.renal_lookup_logs;
create policy "pharmacy admins delete calculation logs"
on public.renal_lookup_logs
for delete
to authenticated
using (public.is_pharmacy_staff_admin());

revoke all on table public.renal_lookup_logs from anon, authenticated;
grant select, insert, delete on table public.renal_lookup_logs to authenticated;

do $$
declare
  identity_sequence text;
begin
  identity_sequence := pg_get_serial_sequence('public.renal_lookup_logs', 'id');
  if identity_sequence is not null then
    execute format('grant usage, select on sequence %s to authenticated', identity_sequence);
  end if;
end;
$$;

