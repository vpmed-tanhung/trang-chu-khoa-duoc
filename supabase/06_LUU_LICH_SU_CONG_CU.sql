create or replace function public.is_pharmacy_staff_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.pharmacy_staff_members
    where user_id = auth.uid()
      and role = 'admin'
  );
$$;

revoke all on function public.is_pharmacy_staff_admin() from public;
grant execute on function public.is_pharmacy_staff_admin() to authenticated;

